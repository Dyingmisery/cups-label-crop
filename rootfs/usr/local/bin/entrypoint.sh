set -euo pipefail

log()  { echo "[cups-label-crop] $*"; }
warn() { echo "[cups-label-crop] WARN: $*" >&2; }

CONFIG_DIR=${CONFIG_DIR:-/config}
CUPS_CONF_DIR="$CONFIG_DIR/cups"
DRIVER_DIR="$CONFIG_DIR/drivers"
DEFAULTS=/usr/share/cups-label-crop/etc-cups.default
LC_CONF_DIR=/etc/cups-label-crop
LC_CONF="$LC_CONF_DIR/label-crop.conf"

CUPSADMIN=${CUPSADMIN:-admin}
CUPSPASSWORD=${CUPSPASSWORD:-admin}
TARGET_PRINTER=${TARGET_PRINTER:-Label_Printer}
CROP_QUEUE_NAME=${CROP_QUEUE_NAME:-Label_Crop}
CROP_QUEUE_DISPLAY_NAME=${CROP_QUEUE_DISPLAY_NAME:-Label Crop}
CROP_QUEUE_LOCATION=${CROP_QUEUE_LOCATION:-}
DEFAULT_SHEET=${DEFAULT_SHEET:-A4}
LABEL_WIDTH_IN=${LABEL_WIDTH_IN:-4}
LABEL_HEIGHT_IN=${LABEL_HEIGHT_IN:-6}
PADDING_PT=${PADDING_PT:-3}
ROTATE_MODE=${ROTATE_MODE:-auto}
TARGET_MEDIA=${TARGET_MEDIA:-}
PRINTER_URI=${PRINTER_URI:-}
PRINTER_PPD=${PRINTER_PPD:-}
PRINTER_DISPLAY_NAME=${PRINTER_DISPLAY_NAME:-}
ENABLE_AVAHI=${ENABLE_AVAHI:-true}
CUPS_LOG_LEVEL=${CUPS_LOG_LEVEL:-warn}

valid_queue_name() {
    # CUPS queue names: printable, no spaces, '/', '#' or quotes, max 127 chars
    [[ -n "$1" && ${#1} -le 127 && "$1" != *[[:space:]/\#\'\"\\]* ]]
}

# ---------------------------------------------------------------- timezone
if [ -n "${TZ:-}" ] && [ -e "/usr/share/zoneinfo/$TZ" ]; then
    ln -sf "/usr/share/zoneinfo/$TZ" /etc/localtime
    echo "$TZ" > /etc/timezone
fi

# ---------------------------------------------------------------- validate
for q in "$TARGET_PRINTER" "$CROP_QUEUE_NAME"; do
    if ! valid_queue_name "$q"; then
        warn "invalid queue name '$q' (no spaces, '/', '#' or quotes; use Label_Printer, not 'Label Printer')"
        exit 1
    fi
done
if [ "$TARGET_PRINTER" = "$CROP_QUEUE_NAME" ]; then
    warn "TARGET_PRINTER and CROP_QUEUE_NAME are both '$TARGET_PRINTER'; they must differ"
    exit 1
fi
case "$ROTATE_MODE" in auto|0|90|180|270) ;; *) warn "ROTATE_MODE must be auto, 0, 90, 180 or 270"; exit 1 ;; esac
num_re='^[0-9]+([.][0-9]+)?$'
for v in LABEL_WIDTH_IN LABEL_HEIGHT_IN PADDING_PT; do
    if ! [[ ${!v} =~ $num_re ]]; then warn "$v must be a number (got '${!v}')"; exit 1; fi
done

# ---------------------------------------------------------------- /config layout
mkdir -p "$CUPS_CONF_DIR" "$DRIVER_DIR/ppd"
# Filters and backends run as the lp user and read /etc/cups/ppd via /config
chmod a+rx "$CONFIG_DIR"
if [ ! -f "$CUPS_CONF_DIR/cupsd.conf" ]; then
    log "first start: seeding $CUPS_CONF_DIR"
    cp -an "$DEFAULTS/." "$CUPS_CONF_DIR/"
    cp /usr/share/cups-label-crop/cupsd.conf "$CUPS_CONF_DIR/cupsd.conf"
fi
# Image-owned files are refreshed every start so updates reach them;
# user state (cupsd.conf, printers.conf, classes.conf, ppd/, ssl/) is kept.
for f in cups-files.conf raw.types raw.convs snmp.conf; do
    [ -f "$DEFAULTS/$f" ] && cp -f "$DEFAULTS/$f" "$CUPS_CONF_DIR/$f"
done
mkdir -p "$CUPS_CONF_DIR/ppd" "$CUPS_CONF_DIR/ssl"
if [ ! -L /etc/cups ]; then
    rm -rf /etc/cups
    ln -s "$CUPS_CONF_DIR" /etc/cups
fi
chown -R root:lp "$CUPS_CONF_DIR"
chmod 755 "$CUPS_CONF_DIR"
chmod 700 "$CUPS_CONF_DIR/ssl"
sed -i "s/^LogLevel .*/LogLevel $CUPS_LOG_LEVEL/" "$CUPS_CONF_DIR/cupsd.conf"

# ---------------------------------------------------------------- cropper settings
# cupsd does not pass the container environment to filters/backends.
mkdir -p "$LC_CONF_DIR"
W_PT=$(awk -v v="$LABEL_WIDTH_IN" 'BEGIN{printf "%d", v*72+0.5}')
H_PT=$(awk -v v="$LABEL_HEIGHT_IN" 'BEGIN{printf "%d", v*72+0.5}')
cat > "$LC_CONF" <<CONF
# Generated by the cups-label-crop entrypoint at every start. Edit the
# container environment instead of this file.
TARGET_PRINTER=$TARGET_PRINTER
CROP_QUEUE_NAME=$CROP_QUEUE_NAME
LABEL_WIDTH_IN=$LABEL_WIDTH_IN
LABEL_HEIGHT_IN=$LABEL_HEIGHT_IN
LABEL_WIDTH_PT=$W_PT
LABEL_HEIGHT_PT=$H_PT
PADDING_PT=$PADDING_PT
ROTATE_MODE=$ROTATE_MODE
TARGET_MEDIA=$TARGET_MEDIA
CONF
chmod 644 "$LC_CONF"

# ---------------------------------------------------------------- admin user
if id "$CUPSADMIN" >/dev/null 2>&1; then
    usermod -a -G lpadmin "$CUPSADMIN"
else
    useradd -r -M -s /usr/sbin/nologin -G lpadmin "$CUPSADMIN"
fi
echo "$CUPSADMIN:$CUPSPASSWORD" | chpasswd
if [ "$CUPSPASSWORD" = "admin" ]; then
    warn "CUPSPASSWORD is the default 'admin'. Change it in the container settings."
fi

# ---------------------------------------------------------------- vendor drivers
# Drop .deb files in /config/drivers; they are installed at every start so
# they survive image updates. PPDs in /config/drivers/ppd show up in the UI.
shopt -s nullglob
debs=("$DRIVER_DIR"/*.deb)
need=()
for deb in "${debs[@]}"; do
    pkg=$(dpkg-deb -f "$deb" Package 2>/dev/null || true)
    ver=$(dpkg-deb -f "$deb" Version 2>/dev/null || true)
    if [ -z "$pkg" ]; then warn "skipping $deb (not a valid .deb)"; continue; fi
    have=$(dpkg-query -W -f '${Version}' "$pkg" 2>/dev/null || true)
    [ "$have" = "$ver" ] || need+=("$deb")
done
if [ ${#need[@]} -gt 0 ]; then
    log "installing ${#need[@]} driver package(s) from $DRIVER_DIR"
    export DEBIAN_FRONTEND=noninteractive
    if ! apt-get install -y --no-install-recommends "${need[@]}"; then
        log "retrying driver install after apt-get update (dependencies needed)"
        if ! { apt-get update && apt-get install -y --no-install-recommends "${need[@]}"; }; then
            warn "driver install failed; see the log above. CUPS will start anyway."
        fi
    fi
fi
model_dir=/usr/share/cups/model/cups-label-crop-drivers
rm -rf "$model_dir"
ppds=("$DRIVER_DIR"/ppd/*.ppd "$DRIVER_DIR"/ppd/*.ppd.gz "$DRIVER_DIR"/*.ppd "$DRIVER_DIR"/*.ppd.gz)
if [ ${#ppds[@]} -gt 0 ]; then
    mkdir -p "$model_dir"
    cp -f "${ppds[@]}" "$model_dir/"
    log "added ${#ppds[@]} PPD file(s) from $DRIVER_DIR"
fi
if [ -f "$DRIVER_DIR/install.sh" ]; then
    log "running $DRIVER_DIR/install.sh"
    bash "$DRIVER_DIR/install.sh" || warn "$DRIVER_DIR/install.sh failed"
fi
shopt -u nullglob

# ---------------------------------------------------------------- dbus + avahi
mkdir -p /run/dbus /run/avahi-daemon
rm -f /run/dbus/pid /run/avahi-daemon/pid
if [ "$ENABLE_AVAHI" = "true" ]; then
    dbus-daemon --system --fork
    if ! avahi-daemon --daemonize --no-chroot; then
        warn "avahi-daemon failed to start; AirPrint discovery will not work (is the container on host networking?)"
    fi
else
    log "ENABLE_AVAHI=false: not advertising printers over mDNS/AirPrint"
fi

# ---------------------------------------------------------------- cupsd
mkdir -p /run/cups /var/spool/cups/tmp /var/log/cups
rm -f /run/cups/cupsd.pid
/usr/sbin/cupsd -f &
CUPSD_PID=$!
stop() {
    log "stopping"
    kill -TERM "$CUPSD_PID" 2>/dev/null || true
    wait "$CUPSD_PID" 2>/dev/null || true
    if [ "$ENABLE_AVAHI" = "true" ]; then avahi-daemon --kill 2>/dev/null || true; fi
    exit 0
}
trap stop TERM INT

for _ in $(seq 1 60); do
    lpstat -r >/dev/null 2>&1 && break
    kill -0 "$CUPSD_PID" 2>/dev/null || { warn "cupsd exited during startup"; exit 1; }
    sleep 0.5
done
lpstat -r >/dev/null 2>&1 || { warn "cupsd did not become ready"; exit 1; }

cupsctl --share-printers --remote-admin --remote-any || warn "cupsctl failed"

# ---------------------------------------------------------------- optional real printer
if [ -n "$PRINTER_URI" ]; then
    if lpstat -p "$TARGET_PRINTER" >/dev/null 2>&1; then
        log "printer $TARGET_PRINTER already exists; leaving it as configured in the web UI"
    else
        args=(-p "$TARGET_PRINTER" -v "$PRINTER_URI" -E -o printer-is-shared=true)
        [ -n "$PRINTER_DISPLAY_NAME" ] && args+=(-D "$PRINTER_DISPLAY_NAME")
        if [ -n "$PRINTER_PPD" ]; then
            if [ -f "$PRINTER_PPD" ]; then args+=(-P "$PRINTER_PPD"); else args+=(-m "$PRINTER_PPD"); fi
        else
            case "$PRINTER_URI" in
                ipp://*|ipps://*) args+=(-m everywhere) ;;
                *) warn "PRINTER_URI is set but PRINTER_PPD is empty; the printer is created without a driver" ;;
            esac
        fi
        if lpadmin "${args[@]}"; then
            log "created printer $TARGET_PRINTER -> $PRINTER_URI"
            if [ "$W_PT" = 288 ] && [ "$H_PT" = 432 ]; then
                for m in w288h432 Custom.4x6in 4x6in 4x6; do
                    if lpoptions -p "$TARGET_PRINTER" -l 2>/dev/null | grep -q -- "$m"; then
                        lpadmin -p "$TARGET_PRINTER" -o "media-default=$m" -o "PageSize=$m" 2>/dev/null || true
                        break
                    fi
                done
            fi
        else
            warn "could not create $TARGET_PRINTER from PRINTER_URI/PRINTER_PPD; add it in the web UI instead"
        fi
    fi
fi

# ---------------------------------------------------------------- crop queue
# If CROP_QUEUE_NAME was changed, remove the old crop queue so iOS does not
# keep showing it (only queues using the labelcrop: backend are touched).
{ lpstat -v 2>/dev/null || true; } | sed -n 's/^device for \([^:]*\): labelcrop:.*/\1/p' | while read -r old; do
    if [ "$old" != "$CROP_QUEUE_NAME" ]; then
        log "removing old crop queue $old (CROP_QUEUE_NAME is now $CROP_QUEUE_NAME)"
        lpadmin -x "$old" || true
    fi
done
crop_args=(-p "$CROP_QUEUE_NAME" -P /usr/share/cups-label-crop/label-crop.ppd
           -v "labelcrop:$TARGET_PRINTER" -D "$CROP_QUEUE_DISPLAY_NAME"
           -o printer-is-shared=true -o printer-error-policy=retry-job
           -o "PageSize=$DEFAULT_SHEET" -E)
[ -n "$CROP_QUEUE_LOCATION" ] && crop_args+=(-L "$CROP_QUEUE_LOCATION")
if lpadmin "${crop_args[@]}"; then
    cupsaccept "$CROP_QUEUE_NAME" || true
    cupsenable "$CROP_QUEUE_NAME" || true
    log "crop queue '$CROP_QUEUE_DISPLAY_NAME' ($CROP_QUEUE_NAME) -> $TARGET_PRINTER, label ${LABEL_WIDTH_IN}x${LABEL_HEIGHT_IN} in"
else
    warn "could not create crop queue $CROP_QUEUE_NAME"
fi
if ! lpstat -p "$TARGET_PRINTER" >/dev/null 2>&1; then
    warn "target printer '$TARGET_PRINTER' is not in CUPS yet. Add your label printer at http://<server-ip>:631 with exactly that queue name. Jobs sent to '$CROP_QUEUE_DISPLAY_NAME' wait and retry until it exists."
fi

log "ready: web UI on port 631 (admin user '$CUPSADMIN')"
wait "$CUPSD_PID"
